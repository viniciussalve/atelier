import type { Asset, CriterionId, Folder, LibraryData, Score, Scorecard } from "./types.ts";

const now = "2026-10-19T12:00:00.000Z";

type AssetSeed = Pick<Asset, "id" | "kind" | "name" | "folderIds" | "tags"> & Partial<Asset>;

export function makeAsset(partial: AssetSeed): Asset {
  return {
    notes: "",
    url: "",
    verdict: "",
    criteria: {},
    license: "",
    weights: "",
    style: "",
    iconKey: "",
    samples: [],
    family: "",
    format: "",
    sizeLabel: "",
    createdAt: now,
    modifiedAt: now,
    importedAt: now,
    lastUsedAt: null,
    ...partial,
  };
}

function scores(
  values: Partial<Record<CriterionId, Score>>,
  notes: Partial<Record<CriterionId, string>> = {},
): Scorecard {
  const card: Scorecard = {};
  for (const [id, value] of Object.entries(values) as [CriterionId, Score][]) {
    card[id] = { value, note: notes[id] ?? "" };
  }
  return card;
}

